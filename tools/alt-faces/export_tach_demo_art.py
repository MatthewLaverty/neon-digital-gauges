"""Export art for the tach demo sketch (Waveshare ESP32-S3-LCD-2.8C, 480x480): day and night tach faces with the
odometer readout baked in (run-length encoded RGB565, decoded into PSRAM at boot), needle (RGB565 + alpha, day and
night colours) and hub. Angle convention: 0 = straight up, positive = clockwise; rpm angle = -115.6 + rpm*0.02885."""
import sys, json, numpy as np
from PIL import Image
for p in ('tools/night','tools/odo'): sys.path.insert(0,p)
import night_preview as npv, seg7
F=json.load(open('art/faces/faces.json'))['gauges']['tach']; N=json.load(open('art/needles/needles.json'))['gauges']['tach']
def rgb565(a): a=a.astype(np.uint16); return ((a[...,0]>>3)<<11)|((a[...,1]>>2)<<5)|(a[...,2]>>3)
def rle(v):
    v=v.ravel(); out=[]; i=0
    while i<len(v):
        j=i
        while j<len(v) and v[j]==v[i] and j-i<65535: j+=1
        out+= [j-i, int(v[i])]; i=j
    return out
face=np.asarray(Image.open('art/faces/tach_480.png').convert('RGB')).astype(float)
day=seg7.draw_field(face.copy(),'odo',123416)
nf=npv.night_face(face.astype(np.uint8)); hm=npv.halo(nf.shape,F['pivot_px'],F['hub_radius_mm']*F['px_per_mm'])
nf=nf*(1-hm[...,None])+npv.C[npv.H['color']]*hm[...,None]; night=seg7.draw_field(nf,'odo',123416)
L=['// Generated by tools/alt-faces/export_tach_demo_art.py -- do not edit.','#pragma once','#include <stdint.h>',
   f'#define FACE_PIVOT_X {F["pivot_px"][0]:.1f}f','#define FACE_PIVOT_Y %.1ff'%F['pivot_px'][1]]
for nm,im in (('day',day),('night',night)):
    r=rle(rgb565(np.clip(im,0,255).astype(np.uint8))); L.append(f'static const uint16_t face_{nm}_rle[{len(r)}] = {{'+','.join(map(str,r))+'};')
    print(nm,'rle words',len(r))
for nm,night_ in (('day',False),('night',True)):
    nd=np.asarray(npv.needle_img(f"art/needles/{N['needle_png']}",night_)).astype(np.uint8)
    L.append(f'static const uint16_t needle_{nm}_rgb[{nd.shape[0]*nd.shape[1]}] = {{'+','.join(map(str,rgb565(nd[...,:3]).ravel()))+'};')
    L.append(f'static const uint8_t needle_{nm}_a[{nd.shape[0]*nd.shape[1]}] = {{'+','.join(map(str,nd[...,3].ravel()))+'};')
h,w=nd.shape[:2]; L+= [f'#define NEEDLE_W {w}',f'#define NEEDLE_H {h}',f'#define NEEDLE_PIVOT_X {N["pivot_px"][0]:.1f}f',f'#define NEEDLE_PIVOT_Y {N["pivot_px"][1]:.1f}f']
hub=np.asarray(Image.open(f"art/needles/{N['hub_png']}").convert('RGBA')).astype(np.uint8)
L+= [f'#define HUB_W {hub.shape[1]}',f'#define HUB_H {hub.shape[0]}',
     f'static const uint16_t hub_rgb[{hub.shape[0]*hub.shape[1]}] = {{'+','.join(map(str,rgb565(hub[...,:3]).ravel()))+'};',
     f'static const uint8_t hub_a[{hub.shape[0]*hub.shape[1]}] = {{'+','.join(map(str,hub[...,3].ravel()))+'};']
open('firmware/tach-demo/tach_demo/tach_art.h','w').write('\n'.join(L)+'\n')
Image.fromarray(np.clip(night,0,255).astype(np.uint8)).save('/tmp/tach_night_base.png'); print('ok')
