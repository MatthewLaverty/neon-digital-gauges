"""Export art for the tach demo sketch (Waveshare ESP32-S3-LCD-2.8C, 480x480): day and night tach faces with the
odometer readout baked in (run-length encoded RGB565, decoded into PSRAM at boot), needle (RGB565 + alpha, day and
night colours) and hub. Angle convention: 0 = straight up, positive = clockwise; rpm angle = -115.6 + rpm*0.02885.

Display scale (owner 2026-10-26: "tach art should maximize display size, not clearance to bezel"): the composed faces,
needle and hub are scaled together about the pivot so the outermost printed pixel sits OUTER_MARGIN_MM inside the
overlay v4 tach opening (r 34.31 mm on the 2.8C; 480 px = O70.13 mm). The base art covers 86.2 mm at 480 px (about
0.81 of stock on this screen); the result is about 0.877 of stock. Production firmware should re-render from
art/faces/cluster_master_10pxmm.png at this scale instead of upsampling the 480 px art."""
import sys, json, numpy as np, cv2
from PIL import Image
for p in ('tools/night','tools/odo'): sys.path.insert(0,p)
import night_preview as npv, seg7
F=json.load(open('art/faces/faces.json'))['gauges']['tach']; N=json.load(open('art/needles/needles.json'))['gauges']['tach']
def rgb565(a): a=a.astype(np.uint16); return ((a[...,0]>>3)<<11)|((a[...,1]>>2)<<5)|(a[...,2]>>3)
def rle(v):
    v=v.ravel(); out=[]; i=0
    while i<len(v):
        j=i
        while j<len(v) and v[j]==v[i] and j-i<65535: j+=1
        out+= [j-i, int(v[i])]; i=j
    return out
face=np.asarray(Image.open('art/faces/tach_480.png').convert('RGB')).astype(float)
day=seg7.draw_field(face.copy(),'odo',123416)
nf=npv.night_face(face.astype(np.uint8)); hm=npv.halo(nf.shape,F['pivot_px'],F['hub_radius_mm']*F['px_per_mm'])
nf=nf*(1-hm[...,None])+npv.C[npv.H['color']]*hm[...,None]; night=seg7.draw_field(nf,'odo',123416)
OPENING_R_MM, OUTER_MARGIN_MM, SCREEN_PX_PER_MM = 34.31, 0.1, 480 / 70.13
yy, xx = np.mgrid[:480, :480]; RR = np.hypot(xx + .5 - F['pivot_px'][0], yy + .5 - F['pivot_px'][1])
lit_r = RR[face.max(-1) > 60].max()                               # outermost printed pixel, px
K = (OPENING_R_MM - OUTER_MARGIN_MM) * SCREEN_PX_PER_MM / lit_r
ART_SCALE = K * F['px_per_mm'] / SCREEN_PX_PER_MM               # fraction of stock size on the screen
print(f'display scale x{K:.4f}: outer print r {lit_r/SCREEN_PX_PER_MM:.2f} -> {lit_r*K/SCREEN_PX_PER_MM:.2f} mm, art {ART_SCALE:.3f} of stock')
def grow(im):                                                     # scale an HxWx3 float image about the pivot
    cx, cy = F['pivot_px']; M = np.array([[K, 0, cx - K * cx], [0, K, cy - K * cy]], np.float32)
    out = cv2.warpAffine(np.clip(im, 0, 255).astype(np.float32), M, (480, 480), flags=cv2.INTER_CUBIC, borderValue=0)
    return np.clip(out, 0, 255) * (RR <= OPENING_R_MM * SCREEN_PX_PER_MM + 1)[..., None]
day, night = grow(day), grow(night)
def grow_rgba(im, pv):                                            # needle / hub: resize, pivot scales with it
    h, w = im.shape[:2]; W2, H2 = int(round(w * K)), int(round(h * K))
    return cv2.resize(im, (W2, H2), interpolation=cv2.INTER_CUBIC), (pv[0] * W2 / w, pv[1] * H2 / h)
L=['// Generated by tools/alt-faces/export_tach_demo_art.py -- do not edit.',f'// Display scale x{K:.4f} (art {ART_SCALE:.3f} of stock): outer print at r {OPENING_R_MM-OUTER_MARGIN_MM:.2f} mm, overlay v4 opening r {OPENING_R_MM} mm.','#pragma once','#include <stdint.h>',
   f'#define FACE_PIVOT_X {F["pivot_px"][0]:.1f}f','#define FACE_PIVOT_Y %.1ff'%F['pivot_px'][1]]
for nm,im in (('day',day),('night',night)):
    r=rle(rgb565(np.clip(im,0,255).astype(np.uint8))); L.append(f'static const uint16_t face_{nm}_rle[{len(r)}] = {{'+','.join(map(str,r))+'};')
    print(nm,'rle words',len(r))
for nm,night_ in (('day',False),('night',True)):
    nd0=np.asarray(npv.needle_img(f"art/needles/{N['needle_png']}",night_)).astype(np.float32)
    nd, npv_px = grow_rgba(nd0, N['pivot_px']); nd = np.clip(nd, 0, 255).astype(np.uint8)
    L.append(f'static const uint16_t needle_{nm}_rgb[{nd.shape[0]*nd.shape[1]}] = {{'+','.join(map(str,rgb565(nd[...,:3]).ravel()))+'};')
    L.append(f'static const uint8_t needle_{nm}_a[{nd.shape[0]*nd.shape[1]}] = {{'+','.join(map(str,nd[...,3].ravel()))+'};')
h,w=nd.shape[:2]; L+= [f'#define NEEDLE_W {w}',f'#define NEEDLE_H {h}',f'#define NEEDLE_PIVOT_X {npv_px[0]:.1f}f',f'#define NEEDLE_PIVOT_Y {npv_px[1]:.1f}f']
hub0=np.asarray(Image.open(f"art/needles/{N['hub_png']}").convert('RGBA')).astype(np.float32)
hub=np.clip(grow_rgba(hub0,(0,0))[0],0,255).astype(np.uint8)
L+= [f'#define HUB_W {hub.shape[1]}',f'#define HUB_H {hub.shape[0]}',
     f'static const uint16_t hub_rgb[{hub.shape[0]*hub.shape[1]}] = {{'+','.join(map(str,rgb565(hub[...,:3]).ravel()))+'};',
     f'static const uint8_t hub_a[{hub.shape[0]*hub.shape[1]}] = {{'+','.join(map(str,hub[...,3].ravel()))+'};']
open('firmware/tach-demo/tach_demo/tach_art.h','w').write('\n'.join(L)+'\n')
Image.fromarray(np.clip(night,0,255).astype(np.uint8)).save('/tmp/tach_night_base.png'); print('ok')
