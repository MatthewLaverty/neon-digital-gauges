"""Export the knob demo art (240x240 JPEG, day faces) into firmware/knob-demo/knob_demo/knob_art.h for the Arduino sketch."""
import sys, io; sys.path.insert(0,'tools/knob'); import knob_mock as km
from PIL import ImageOps
F={k:(km.rnd(a),km.rnd(b)) for k,(a,b) in km.faces(False).items()}
F['odo']=(km.odo_stop('odo',123416),km.odo_stop('trip',287.4))
imgs={'temp':F['temp'][0],'temp_oil':F['temp'][1],'fuel':F['fuel'][0],'fuel_e85':F['fuel'][1],'tach':F['tach'][0],'tach_boost':F['tach'][1],
      'odo':F['odo'][0],'trip':F['odo'][1],'trip_zero':km.odo_stop('trip',0.0),'speedo':F['speedo'][0],'speedo_data':F['speedo'][1]}
out=['// Generated by tools/knob/export_knob_art.py -- do not edit. 240x240 JPEG faces for the knob demo.','#pragma once','#include <stdint.h>']
for k,im in imgs.items():
    b=io.BytesIO(); im.convert('RGB').save(b,'JPEG',quality=90); d=b.getvalue()
    out.append(f'static const uint8_t img_{k}[{len(d)}] = {{'+','.join(str(x) for x in d)+'};')
    im.save(f'/tmp/knob_{k}.png')
open('firmware/knob-demo/knob_demo/knob_art.h','w').write('\n'.join(out)+'\n'); print('ok', sum(len(l) for l in out)//1024,'KB text')
